def q(
    item_id: str,
    title: str,
    mission: str,
    story: str,
    prompt: str,
    answer: str,
    explanation: str,
    knowledge_point: str,
    options: list[str] | None = None,
    input_type: str | None = None,
    hero: str = "",
    option_icons: dict[str, str] | None = None,
    audio_text: str = "",
) -> dict:
    row = {
        "kind": "question",
        "item_id": item_id,
        "title": title,
        "mission": mission,
        "story": story,
        "prompt": prompt,
        "answer": answer,
        "explanation": explanation,
        "knowledge_point": knowledge_point,
        "difficulty": "亲子玩一玩",
        "source_label": SOURCE,
    }
    if options:
        row["options"] = options
    if input_type and input_type not in {"number", "text"}:
        if isinstance(hero, dict) and not option_icons:
            option_icons = hero
            hero = input_type
        elif not hero:
            hero = input_type
        input_type = None
    if isinstance(hero, dict) and not option_icons:
        option_icons = hero
        hero = ""
    if input_type:
        row["input_type"] = input_type
    if hero:
        row["hero"] = hero
    if option_icons:
        row["option_icons"] = option_icons
    if audio_text:
        row["audio_text"] = audio_text
    return row


