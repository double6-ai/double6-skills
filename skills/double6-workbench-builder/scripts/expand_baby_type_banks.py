    data = json.loads(ROOT.read_text(encoding="utf-8"))
    baby = next(stage for stage in data["stages"] if stage["stage_id"] == "baby-growth-explorer")
    extras = clone_more_for_rest()
    extras["education-math"] = MORE["education-math"]
    extras["education-language"] = MORE["education-language"]

    modules = baby["modules"]
    math_items = [row for row in modules["education-math"] if row["item_id"] != "baby-math-02"]
    math_items.extend(COMPARE)
    modules["education-math"] = math_items

    for module_id, by_point in extras.items():
        existing_ids = {row["item_id"] for row in modules[module_id]}
        for rows in by_point.values():
            for row in rows:
                if row["item_id"] not in existing_ids:
                    modules[module_id].append(row)
                    existing_ids.add(row["item_id"])

    ROOT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    baby = next(stage for stage in data["stages"] if stage["stage_id"] == "baby-growth-explorer")
    for module_id, items in baby["modules"].items():
        if module_id == "education-errors":
            continue
        points: dict[str, int] = {}
        for item in items:
            points[item["knowledge_point"]] = points.get(item["knowledge_point"], 0) + 1
        print(module_id, len(items), points)


